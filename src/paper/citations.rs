#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum FieldCheck {
    Verified,
    Mismatch { expected: String, found: String },
    Unknown { reason: String },
    NotApplicable,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct CitationCheck {
    pub key: String,
    pub id: Option<String>,
    pub fields: BTreeMap<String, FieldCheck>,
    pub verified: bool,
    pub sources: Vec<SourceTag>,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct CitationReport {
    pub checks: Vec<CitationCheck>,
    pub unknown_keys: Vec<(String, String)>,
    pub blocking: Vec<String>,
    pub manuscript_hash: String,
}

pub fn normalize_doi(value: &str) -> Option<String> {
    let lower = value.trim().to_lowercase();
    let mut s = lower.as_str();
    for prefix in ["https://doi.org/", "http://dx.doi.org/", "doi:"] {
        if let Some(rest) = s.strip_prefix(prefix) {
            s = rest.trim();
            break;
        }
    }
    s = s.trim_end_matches(|c: char| ".,;:)]}>\"'".contains(c));
    (s.starts_with("10.") && s.contains('/')).then(|| s.to_owned())
}
pub fn normalize_openalex(value: &str) -> Option<String> {
    let s = value.trim();
    let s = if s.to_ascii_lowercase().starts_with("https://openalex.org/") {
        &s[21..]
    } else {
        s
    };
    let bytes = s.as_bytes();
    if bytes.len() < 2
        || !bytes[0].eq_ignore_ascii_case(&b'w')
        || !bytes[1..].iter().all(u8::is_ascii_digit)
    {
        return None;
    }
    Some(format!("W{}", &s[1..]))
}

// Canonical decompositions containing combining marks, generated from Unicode data.
fn deaccent(c: char) -> Option<&'static str> {
    DECOMPOSITIONS
        .binary_search_by_key(&c, |entry| entry.0)
        .ok()
        .map(|i| DECOMPOSITIONS[i].1)
}
fn is_mark(c: char) -> bool {
    let n = c as u32;
    MARK_RANGES
        .binary_search_by(|&(start, end)| {
            if n < start {
                std::cmp::Ordering::Greater
            } else if n > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
fn fold(s: &str) -> String {
    let mut result = String::new();
    let mut separator = false;
    for c in s.chars().flat_map(char::to_lowercase) {
        if is_mark(c) {
            continue;
        }
        let decomposed = deaccent(c)
            .map(str::to_owned)
            .unwrap_or_else(|| c.to_string());
        for d in decomposed.chars() {
            if d.is_alphanumeric() {
                if separator && !result.is_empty() {
                    result.push(' ');
                }
                separator = false;
                result.push(d);
            } else {
                separator = true;
            }
        }
    }
    result
}
fn family(name: &str) -> String {
    let s = if let Some((family, _)) = name.split_once(',') {
        family
    } else {
        name.split_whitespace().last().unwrap_or("")
    };
    fold(s)
}
fn venue_matches(bib: &str, record: &str) -> bool {
    let a = fold(bib);
    let b = fold(record);
    if a == b {
        return true;
    }
    let stop = |s: &&str| !matches!(*s, "of" | "the" | "and" | "for" | "de" | "la");
    let a: Vec<_> = a.split_whitespace().filter(stop).collect();
    let b: Vec<_> = b.split_whitespace().filter(stop).collect();
    !a.is_empty() && a.len() == b.len() && a.iter().zip(b).all(|(x, y)| y.starts_with(x))
}
fn compare(
    expected: &str,
    found: Option<String>,
    matches: impl Fn(&str, &str) -> bool,
) -> FieldCheck {
    match found.filter(|s| !s.trim().is_empty()) {
        Some(found) if matches(expected, &found) => FieldCheck::Verified,
        Some(found) => FieldCheck::Mismatch {
            expected: expected.to_owned(),
            found,
        },
        None => FieldCheck::Unknown {
            reason: "source does not report field".into(),
        },
    }
}
fn aggregate(checks: Vec<FieldCheck>) -> FieldCheck {
    if let Some(c) = checks
        .iter()
        .find(|c| matches!(c, FieldCheck::Mismatch { .. }))
    {
        return c.clone();
    }
    if checks.iter().any(|c| matches!(c, FieldCheck::Verified)) {
        return FieldCheck::Verified;
    }
    FieldCheck::Unknown {
        reason: "no source reports field".into(),
    }
}
fn record_pages(w: &WorkMeta) -> Option<String> {
    w.first_page.as_ref().map(|f| match &w.last_page {
        Some(l) => format!("{f}-{l}"),
        None => f.clone(),
    })
}
pub fn verify_entry(
    e: &BibEntry,
    crossref: &dyn Fn(&str) -> Res<Option<WorkMeta>>,
    openalex: &dyn Fn(&str) -> Res<Option<WorkMeta>>,
) -> CitationCheck {
    let doi = e.doi.as_deref().and_then(normalize_doi);
    let id = doi
        .clone()
        .or_else(|| e.openalex.as_deref().and_then(normalize_openalex));
    let mut records = Vec::new();
    if let Some(d) = &doi {
        if let Ok(Some(w)) = crossref(d) {
            records.push(w);
        }
    }
    if let Some(id) = &id {
        if let Ok(Some(w)) = openalex(id) {
            records.push(w);
        }
    }
    let mut fields = BTreeMap::new();
    for name in [
        "authors",
        "title",
        "year",
        "venue",
        "pages",
        "article_number",
    ] {
        let absent = match name {
            "authors" => e.authors.is_empty(),
            "title" => e.title.trim().is_empty(),
            "year" => e.year.is_none(),
            "venue" => e.venue.as_ref().is_none_or(|s| s.trim().is_empty()),
            "pages" => e.pages.as_ref().is_none_or(|s| s.trim().is_empty()),
            _ => e
                .article_number
                .as_ref()
                .is_none_or(|s| s.trim().is_empty()),
        };
        let result = if absent {
            if matches!(name, "authors" | "title" | "year") {
                FieldCheck::Unknown {
                    reason: "bibliography field missing".into(),
                }
            } else {
                FieldCheck::NotApplicable
            }
        } else {
            aggregate(
                records
                    .iter()
                    .map(|w| match name {
                        "title" => compare(&e.title, w.title.clone(), |a, b| fold(a) == fold(b)),
                        "authors" => {
                            if w.authors.is_empty() {
                                FieldCheck::Unknown {
                                    reason: "source does not report authors".into(),
                                }
                            } else if e.authors.len() == w.authors.len()
                                && e.authors
                                    .iter()
                                    .zip(&w.authors)
                                    .all(|(a, b)| family(a) == family(b))
                            {
                                FieldCheck::Verified
                            } else {
                                FieldCheck::Mismatch {
                                    expected: e.authors.join(" and "),
                                    found: w.authors.join(" and "),
                                }
                            }
                        }
                        "year" => compare(
                            &e.year.unwrap().to_string(),
                            w.year.map(|y| y.to_string()),
                            |a, b| a == b,
                        ),
                        "venue" => {
                            compare(e.venue.as_deref().unwrap(), w.venue.clone(), venue_matches)
                        }
                        "pages" => {
                            let p = e.pages.as_deref().unwrap();
                            let single = !p.contains('-') && !p.chars().any(char::is_whitespace);
                            if single
                                && w.article_number
                                    .as_deref()
                                    .is_some_and(|n| n.eq_ignore_ascii_case(p))
                            {
                                FieldCheck::Verified
                            } else {
                                compare(
                                    p,
                                    record_pages(w).or_else(|| {
                                        if single {
                                            w.article_number.clone()
                                        } else {
                                            None
                                        }
                                    }),
                                    |a, b| a.trim().eq_ignore_ascii_case(b.trim()),
                                )
                            }
                        }
                        _ => compare(
                            e.article_number.as_deref().unwrap(),
                            w.article_number.clone(),
                            |a, b| a.trim().eq_ignore_ascii_case(b.trim()),
                        ),
                    })
                    .collect(),
            )
        };
        fields.insert(name.to_owned(), result);
    }
    let verified = id.is_some()
        && !records.is_empty()
        && fields
            .values()
            .all(|c| matches!(c, FieldCheck::Verified | FieldCheck::NotApplicable));
    CitationCheck {
        key: e.key.clone(),
        id,
        fields,
        verified,
        sources: records.into_iter().map(|w| w.source).collect(),
    }
}
pub fn verify_manuscript(
    ms: &Manuscript,
    bib: &Bibliography,
    crossref: &dyn Fn(&str) -> Res<Option<WorkMeta>>,
    openalex: &dyn Fn(&str) -> Res<Option<WorkMeta>>,
) -> CitationReport {
    let mut unknown_keys = Vec::new();
    let mut blocking = Vec::new();
    let mut cited = std::collections::BTreeSet::new();
    for (location, keys) in ms.invariants().citations {
        for key in keys {
            if bib.entries.iter().any(|e| e.key == key) {
                cited.insert(key);
            } else {
                blocking.push(format!("unknown bib key {key} at {location}"));
                unknown_keys.push((location.clone(), key));
            }
        }
    }
    let checks = cited
        .into_iter()
        .map(|key| {
            let e = bib.entries.iter().find(|e| e.key == key).unwrap();
            let check = verify_entry(e, crossref, openalex);
            if !check.verified {
                blocking.push(format!("unverified citation {key}"));
            }
            check
        })
        .collect();
    CitationReport {
        checks,
        unknown_keys,
        blocking,
        manuscript_hash: ms.hash(),
    }
}

